create or replace TRIGGER T_COST_ROLLUP_UPDATE
FOR INSERT OR UPDATE ON COST_ROLLUP_CHANGE
COMPOUND TRIGGER

  -- Temporary collection to store new/updated rows
  TYPE t_row IS TABLE OF COST_ROLLUP_CHANGE%ROWTYPE;
  g_rows t_row := t_row();

  -- Before each row: capture the new row
  BEFORE EACH ROW IS
  BEGIN
    g_rows.EXTEND;
    g_rows(g_rows.LAST).BOM_KEY := :NEW.BOM_KEY;
    g_rows(g_rows.LAST).USER_KEY := :NEW.USER_KEY;
    g_rows(g_rows.LAST).EFFECTIVE_DATE := :NEW.EFFECTIVE_DATE;
  END BEFORE EACH ROW;

  -- After statement: process all collected rows
  AFTER STATEMENT IS
  BEGIN
    FOR i IN 1 .. g_rows.COUNT LOOP
      -- Call  procedure
      GET_BOM_HIERARCHY_WITH_COST(
        g_rows(i).BOM_KEY,
        g_rows(i).USER_KEY,
        g_rows(i).EFFECTIVE_DATE
      );

      -- Delete the processed row
     DELETE FROM COST_ROLLUP_CHANGE
     WHERE BOM_KEY = g_rows(i).BOM_KEY
     AND USER_KEY = g_rows(i).USER_KEY
     AND EFFECTIVE_DATE = g_rows(i).EFFECTIVE_DATE;
    END LOOP;
  END AFTER STATEMENT;

END T_COST_ROLLUP_UPDATE;


--
--Below procedure will updates all the child boms data in BOM_HEADER,BOM_LINE_ITEM based on BOM_KEY supplied.
--Dynamically generate the update queries and updates the data. If any input parameter is NULL then it will 
--not include in the UPDATE Query
--
CREATE OR REPLACE PROCEDURE updateChildBomsData ( p_bom_key IN BOM_HEADER.BOM_KEY%TYPE,
p_effective_from_date IN BOM_HEADER.EFFECTIVE_FROM_DT%TYPE,
p_effective_to_date IN BOM_HEADER.EFFECTIVE_TO_DT%TYPE,
p_status IN BOM_HEADER.STATUS%TYPE ) AS

  v_last_bomkey  BOM_HEADER.BOM_KEY%TYPE;
  v_sql       VARCHAR2(4000);
  v_set       VARCHAR2(4000) := NULL;
  v_rows      PLS_INTEGER;
  cur INTEGER;

 CURSOR cur_childBoms IS
    WITH BOM_HIERARCHY (
      LEVEL_NO,
      PARENT_BOM_KEY,
      BOM_KEY,
      SUB_BOM_KEY,
      ITEM_KEY,
      ITEM_QUANTITY,
      EFFECTIVE_FROM_DT,
      EFFECTIVE_TO_DT,
      VERSION,
      BOM_PATH
    ) AS (
      SELECT
        1 AS LEVEL_NO,
        NULL AS PARENT_BOM_KEY,
        bh.BOM_KEY,
        bli.SUB_BOM_KEY,
        bli.ITEM_KEY,
        bli.ITEM_QUANTITY,
        bli.EFFECTIVE_FROM_DT,
        bli.EFFECTIVE_TO_DT,
        bh.VERSION,
        TO_CHAR(bh.BOM_KEY) AS BOM_PATH
      FROM BOM_HEADER bh
      LEFT JOIN BOM_LINE_ITEM bli ON bh.BOM_KEY = bli.BOM_KEY
      WHERE bh.BOM_KEY = p_bom_key
      UNION ALL
      SELECT
        bh.LEVEL_NO + 1,
        bh.BOM_KEY AS PARENT_BOM_KEY,
        bli.BOM_KEY,
        bli.SUB_BOM_KEY,
        bli.ITEM_KEY,
        bli.ITEM_QUANTITY,
        bli.EFFECTIVE_FROM_DT,
        bli.EFFECTIVE_TO_DT,
        bh.VERSION,
        bh.BOM_PATH || '>' || TO_CHAR(bli.BOM_KEY)
      FROM BOM_LINE_ITEM bli
      JOIN BOM_HIERARCHY bh ON bli.BOM_KEY = bh.SUB_BOM_KEY
    )
    SELECT BOM_KEY
    FROM   BOM_HIERARCHY
    ORDER BY LEVEL_NO;

   v_curr_bom_key BOM_HEADER.BOM_KEY%TYPE;
BEGIN

  OPEN cur_childBoms;
  LOOP
    FETCH cur_childBoms INTO v_curr_bom_key;
    EXIT WHEN cur_childBoms%NOTFOUND;

    IF v_last_bomkey IS NULL OR v_last_bomkey <> v_curr_bom_key THEN
        v_sql := 'UPDATE BOM_HEADER SET UPDATE_DT= :p1 ';
        v_sql := v_sql || CASE WHEN p_effective_from_date IS NOT NULL THEN ' ,EFFECTIVE_FROM_DT = :p2 ' END;
        v_sql := v_sql || CASE WHEN p_effective_to_date IS NOT NULL THEN ' ,EFFECTIVE_TO_DT = :p3 ' END;
        v_sql := v_sql || CASE WHEN p_status IS NOT NULL THEN ' ,STATUS = :p4 ' END;
        v_sql := v_sql || ' WHERE BOM_KEY = :p5 ';

        cur := DBMS_SQL.OPEN_CURSOR;
        DBMS_SQL.PARSE(cur, v_sql, DBMS_SQL.NATIVE);

        DBMS_SQL.BIND_VARIABLE(cur, ':p1',      SYSDATE);
        IF p_effective_from_date IS NOT NULL THEN
            DBMS_SQL.BIND_VARIABLE(cur, ':p2',    p_effective_from_date);
        END IF;
        IF p_effective_to_date IS NOT NULL THEN
            DBMS_SQL.BIND_VARIABLE(cur, ':p3',    p_effective_to_date);
        END IF;
        IF p_status IS NOT NULL THEN
            DBMS_SQL.BIND_VARIABLE(cur, ':p4',    p_status);
        END IF;
        DBMS_SQL.BIND_VARIABLE(cur, ':p5', v_curr_bom_key);

        v_rows := DBMS_SQL.EXECUTE(cur);
        DBMS_SQL.CLOSE_CURSOR(cur);

        v_sql := 'UPDATE BOM_LINE_ITEM SET UPDATE_DT= :p1 ';
        v_sql := v_sql || CASE WHEN p_effective_from_date IS NOT NULL THEN ' ,EFFECTIVE_FROM_DT = :p2 ' END;
        v_sql := v_sql || CASE WHEN p_effective_to_date IS NOT NULL THEN ' ,EFFECTIVE_TO_DT = :p3 ' END;
        v_sql := v_sql || ' WHERE BOM_KEY = :p4 ';

        cur := DBMS_SQL.OPEN_CURSOR;
        DBMS_SQL.PARSE(cur, v_sql, DBMS_SQL.NATIVE);

        DBMS_SQL.BIND_VARIABLE(cur, ':p1',      SYSDATE);
        IF p_effective_from_date IS NOT NULL THEN
        DBMS_SQL.BIND_VARIABLE(cur, ':p2',    p_effective_from_date);
        END IF;
        IF p_effective_to_date IS NOT NULL THEN
        DBMS_SQL.BIND_VARIABLE(cur, ':p3',    p_effective_to_date);
        END IF;
        DBMS_SQL.BIND_VARIABLE(cur, ':p4', v_curr_bom_key);

        v_rows := v_rows + DBMS_SQL.EXECUTE(cur);
        DBMS_SQL.CLOSE_CURSOR(cur);

        --DBMS_OUTPUT.PUT_LINE('Rows updated: ' || v_rows);
        v_last_bomkey := v_curr_bom_key;

    END IF;
  END LOOP;
  COMMIT;
  CLOSE cur_childBoms;

EXCEPTION
  WHEN OTHERS THEN
    IF cur_childBoms%ISOPEN THEN
      CLOSE cur_childBoms;
    END IF;
    -- DBMS_OUTPUT.PUT_LINE('Error: ' || SQLCODE || ' - ' || SQLERRM);
    RAISE;
END updateChildBomsData;

-------------------------------------------------------------------------------------------
-- Compares the two boms hierarchy/structure is same or not for the inputs supplied based on 
-- fields LEVEL_NO, ITEM_IDENTIFIER, ITEM_QUANTITY, VERSION. Assuming EFFECTIVE_FROM_DT,
-- EFFECTIVE_TO_DT are already compared before calling the procedure.
-- This procedure will return 'Y' if both hierarchies are same else 'N'.
--------------------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE COMPARE_BOM_HIERARCHY (
  p_bom_key1          IN  NUMBER,
  p_bom_key2          IN  NUMBER,
  p_set_equal         OUT VARCHAR2  -- 'Y' if sets are equal.

) AS
  v_cnt1        NUMBER;
  v_cnt2        NUMBER;
  v_diff12      NUMBER;
  v_diff21      NUMBER;

BEGIN
  ----------------------------------------------------------------------
  -- Row counts for each hierarchy
  ----------------------------------------------------------------------
  WITH BOM_HIERARCHY (
    LEVEL_NO, PARENT_BOM_KEY, BOM_KEY, SUB_BOM_KEY, ITEM_KEY, ITEM_IDENTIFIER, ITEM_QUANTITY, EFFECTIVE_FROM_DT, EFFECTIVE_TO_DT, VERSION, BOM_PATH
  ) AS (
    SELECT
      1 AS LEVEL_NO,
      NULL AS PARENT_BOM_KEY,
      bh.BOM_KEY,
      bli.SUB_BOM_KEY,
      bli.ITEM_KEY,
      im.ITEM_IDENTIFIER,
      bli.ITEM_QUANTITY,
      bli.EFFECTIVE_FROM_DT,
      bli.EFFECTIVE_TO_DT,
      bh.VERSION,
      TO_CHAR(bh.BOM_KEY) AS BOM_PATH
    FROM BOM_HEADER bh
    LEFT JOIN BOM_LINE_ITEM bli ON bh.BOM_KEY = bli.BOM_KEY
    LEFT JOIN ITEM_MASTER im ON im.ITEM_KEY = bli.ITEM_KEY
    WHERE bh.BOM_KEY = p_bom_key1
    UNION ALL
    SELECT
      bh.LEVEL_NO + 1,
      bh.BOM_KEY AS PARENT_BOM_KEY,
      bli.BOM_KEY,
      bli.SUB_BOM_KEY,
      bli.ITEM_KEY,
      im.ITEM_IDENTIFIER,
      bli.ITEM_QUANTITY,
      bli.EFFECTIVE_FROM_DT,
      bli.EFFECTIVE_TO_DT,
      bh.VERSION,
      bh.BOM_PATH || '>' || TO_CHAR(bli.BOM_KEY)
    FROM BOM_LINE_ITEM bli
    LEFT JOIN ITEM_MASTER im ON im.ITEM_KEY = bli.ITEM_KEY
    JOIN BOM_HIERARCHY bh ON bli.BOM_KEY = bh.SUB_BOM_KEY
  )
  SELECT COUNT(*) INTO v_cnt1 FROM BOM_HIERARCHY;

  WITH BOM_HIERARCHY (
    LEVEL_NO, PARENT_BOM_KEY, BOM_KEY, SUB_BOM_KEY, ITEM_KEY, ITEM_IDENTIFIER, ITEM_QUANTITY, EFFECTIVE_FROM_DT, EFFECTIVE_TO_DT, VERSION, BOM_PATH
  ) AS (
    SELECT
      1 AS LEVEL_NO,
      NULL AS PARENT_BOM_KEY,
      bh.BOM_KEY,
      bli.SUB_BOM_KEY,
      bli.ITEM_KEY,
      im.ITEM_IDENTIFIER,
      bli.ITEM_QUANTITY,
      bli.EFFECTIVE_FROM_DT,
      bli.EFFECTIVE_TO_DT,
      bh.VERSION,
      TO_CHAR(bh.BOM_KEY) AS BOM_PATH
    FROM BOM_HEADER bh
    LEFT JOIN BOM_LINE_ITEM bli ON bh.BOM_KEY = bli.BOM_KEY
    LEFT JOIN ITEM_MASTER im ON im.ITEM_KEY = bli.ITEM_KEY
    WHERE bh.BOM_KEY = p_bom_key2
    UNION ALL
    SELECT
      bh.LEVEL_NO + 1,
      bh.BOM_KEY AS PARENT_BOM_KEY,
      bli.BOM_KEY,
      bli.SUB_BOM_KEY,
      bli.ITEM_KEY,
      im.ITEM_IDENTIFIER,
      bli.ITEM_QUANTITY,
      bli.EFFECTIVE_FROM_DT,
      bli.EFFECTIVE_TO_DT,
      bh.VERSION,
      bh.BOM_PATH || '>' || TO_CHAR(bli.BOM_KEY)
    FROM BOM_LINE_ITEM bli
    LEFT JOIN ITEM_MASTER im ON im.ITEM_KEY = bli.ITEM_KEY
    JOIN BOM_HIERARCHY bh ON bli.BOM_KEY = bh.SUB_BOM_KEY
  )
  SELECT COUNT(*) INTO v_cnt2 FROM BOM_HIERARCHY;

  ----------------------------------------------------------------------
  -- If count does  not match then the boms are not in equal hierarchy
  ----------------------------------------------------------------------
  IF v_cnt1 <> v_cnt2 THEN
    p_set_equal := 'N';
    --DBMS_OUTPUT.PUT_LINE('BOM_KEY1 = ' || p_bom_key1 || ', rows = ' || v_cnt1);
    --DBMS_OUTPUT.PUT_LINE('BOM_KEY2 = ' || p_bom_key2 || ', rows = ' || v_cnt2);
    --DBMS_OUTPUT.PUT_LINE('Set-equality: ' || p_set_equal || ' (counts differ)');
    RETURN; -- stop executing further comparisons
  END IF;

  -------------------------------------------------------------------------------------
  -- Set equality check. If both MINUS directions return zero rows, the sets are equal.
  -------------------------------------------------------------------------------------
  WITH
  BOM_HIERARCHY1 (LEVEL_NO, PARENT_BOM_KEY, BOM_KEY, SUB_BOM_KEY, ITEM_KEY, ITEM_IDENTIFIER, ITEM_QUANTITY, EFFECTIVE_FROM_DT, EFFECTIVE_TO_DT, VERSION, BOM_PATH) AS (
    SELECT
      1 AS LEVEL_NO,
      NULL AS PARENT_BOM_KEY,
      bh.BOM_KEY,
      bli.SUB_BOM_KEY,
      bli.ITEM_KEY,
      im.ITEM_IDENTIFIER,
      bli.ITEM_QUANTITY,
      bli.EFFECTIVE_FROM_DT,
      bli.EFFECTIVE_TO_DT,
      bh.VERSION,
      TO_CHAR(bh.BOM_KEY) AS BOM_PATH
    FROM BOM_HEADER bh
    LEFT JOIN BOM_LINE_ITEM bli ON bh.BOM_KEY = bli.BOM_KEY
    LEFT JOIN ITEM_MASTER im ON im.ITEM_KEY = bli.ITEM_KEY
    WHERE bh.BOM_KEY = p_bom_key1
    UNION ALL
    SELECT
      bh.LEVEL_NO + 1,
