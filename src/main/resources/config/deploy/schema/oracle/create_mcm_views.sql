  SELECT TAM_ITEM_ALLOCATION_ID,TAM_SUPPLIER_ALLOCATION_ID,ITEM_KEY,ALLOCATION FROM 
(
  SELECT * FROM TAM_ITEM_ALLOCATION
  UNION ALL
  (
    SELECT TO_NUMBER(NVL((SELECT MAX(TAM_ITEM_ALLOCATION_ID) FROM  TAM_ITEM_ALLOCATION),0)+ROWNUM) TAM_ITEM_ALLOCATION_ID,TAM_SUPPLIER_ALLOCATION_ID,A.ITEM_KEY,NULL ALLOCATION 
    FROM
    (
      SELECT DISTINCT A.ITEM_KEY,FUNCTIONAL_GROUP_ID,B.BUSINESS_ENTITY_KEY
      FROM ITEM_FG_MAP A
      INNER JOIN
      ITEM_AVL B
      ON
      A.ITEM_KEY = B.ITEM_KEY
    ) A,
    (
    SELECT TAM_SUPPLIER_ALLOCATION_ID,BUSINESS_ENTITY_KEY,A.TAM_ALLOCATION_ID,FUNCTIONAL_GROUP_ID
    FROM 
      (SELECT * FROM TAM_SUPPLIER_ALLOCATION WHERE TAM_SUPPLIER_ALLOCATION_ID NOT IN (SELECT DISTINCT TAM_SUPPLIER_ALLOCATION_ID FROM TAM_ITEM_ALLOCATION)) A,
      TAM_ALLOCATION B
      WHERE A.TAM_ALLOCATION_ID = B.TAM_ALLOCATION_ID
    )B
    WHERE
    A.BUSINESS_ENTITY_KEY = B.BUSINESS_ENTITY_KEY
    AND A.FUNCTIONAL_GROUP_ID = B.FUNCTIONAL_GROUP_ID -- 133
  )
