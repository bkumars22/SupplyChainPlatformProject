  INSERT /*+ APPEND PARALLEL */ INTO TAM_ROLLOVER_SITE_DETAIL_PROCESSING (SITE_KEY, SITE_IDENTIFIER, SITE_DESCRIPTION, SITE_TYPE,PARENT_SITE_KEY,BUSINESS_ENTITY_KEY,SITE_DETAIL_ID,TAM_PROCESSING_FLAG)
