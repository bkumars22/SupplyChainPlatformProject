  BOM_HIERARCHY2 (LEVEL_NO, PARENT_BOM_KEY, BOM_KEY, SUB_BOM_KEY, ITEM_KEY, ITEM_IDENTIFIER, ITEM_QUANTITY, EFFECTIVE_FROM_DT, EFFECTIVE_TO_DT, VERSION, BOM_PATH) AS (
