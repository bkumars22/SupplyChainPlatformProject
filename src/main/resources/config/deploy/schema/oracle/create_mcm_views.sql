-- XLOB Rollover

create or replace PROCEDURE XLOB_ROLLOVER (CURRENT_MONTH_START DATE,NEXT_ROLLOVER DATE,ADD_MONTH_START DATE, ADD_MONTH_END DATE,
               COPY_MONTH_START DATE, COPY_MONTH_END DATE, MAX_ROLLOVER_COUNT NUMBER) AS
CURSOR cur_xlob_alloc IS
SELECT xa.ID as xlobID,fg.status, sd.*
FROM XLOB_ALLOCATION xa, functional_group fg,site s
LEFT JOIN SITE_DETAILS sd on sd.ID = s.SITE_DETAIL_ID
WHERE xa.FUNCTIONAL_GROUP_ID = fg.FUNCTIONAL_GROUP_ID
AND xa.site_key = s.site_key
AND xa.ROLL_OVER_COUNT < MAX_ROLLOVER_COUNT
AND (xa.NEXT_ROLLOVER_DATE < NEXT_ROLLOVER OR (xa.NEXT_ROLLOVER_DATE is null AND xa.CREATED_ON < CURRENT_MONTH_START));

rec_alloc cur_xlob_alloc%ROWTYPE;

BEGIN
  OPEN cur_xlob_alloc;
  LOOP
    FETCH cur_xlob_alloc INTO rec_alloc;
    EXIT WHEN cur_xlob_alloc%NOTFOUND;

    -- Add 12th month

    INSERT INTO XLOB_ITEM_ALLOCATION (ID, XLOB_ALLOCATION_ID, BUSINESS_ENTITY_KEY,ITEM_KEY,MANUFACTURER_PART,START_DATE, END_DATE,CREATED_ON,CREATED_BY,ALLOCATION)
	SELECT XLOB_ITEM_ALLOCATION_SEQ.NEXTVAL, xlobAlloc.ID, xlobPartAlloc.BUSINESS_ENTITY_KEY,xlobPartAlloc.ITEM_KEY,xlobPartAlloc.MANUFACTURER_PART,
	cal.FISCAL_PERIOD_START_DATE, cal.FISCAL_PERIOD_END_DATE,CURRENT_TIMESTAMP,'BATCH',
		(CASE  WHEN (rec_alloc.STATUS = 'ACTIVE' and rec_alloc.tam_visible_flag = '1') THEN xlobPartAlloc.allocation ELSE NULL END)
		FROM XLOB_ALLOCATION xlobAlloc, XLOB_ITEM_ALLOCATION xlobPartAlloc,
	    (SELECT m.FISCAL_PERIOD_START_DATE, m.FISCAL_PERIOD_END_DATE
	     FROM fiscal_period m
	     WHERE m.FISCAL_PERIOD_TYPE = 'M'
	     AND m.FISCAL_PERIOD_START_DATE >= ADD_MONTH_START  -- future month start
	     and m.FISCAL_PERIOD_END_DATE <= ADD_MONTH_END   -- future month end
	    ) cal
	WHERE xlobAlloc.ID = xlobPartAlloc.XLOB_ALLOCATION_ID
	AND xlobPartAlloc.START_DATE = COPY_MONTH_START -- last month start
	AND xlobPartAlloc.END_DATE = COPY_MONTH_END -- last month end
	AND xlobAlloc.ID = rec_alloc.xlobID
	AND NOT EXISTS (SELECT 'x' FROM XLOB_ITEM_ALLOCATION xlobPartAlloc1
	WHERE xlobPartAlloc1.XLOB_ALLOCATION_ID = xlobPartAlloc.XLOB_ALLOCATION_ID
	AND xlobPartAlloc1.BUSINESS_ENTITY_KEY = xlobPartAlloc.BUSINESS_ENTITY_KEY
	AND xlobPartAlloc1.START_DATE = cal.FISCAL_PERIOD_START_DATE
	AND xlobPartAlloc1.END_DATE = cal.FISCAL_PERIOD_END_DATE);

	--update allocation
	
	IF (rec_alloc.tam_visible_flag = '1' and rec_alloc.STATUS = 'ACTIVE') THEN
       UPDATE XLOB_ALLOCATION
       SET NEXT_ROLLOVER_DATE = NEXT_ROLLOVER,
           LAST_CHANGED_BY = 'BATCH',
           LAST_CHANGED_ON= CURRENT_TIMESTAMP,
           ROLL_OVER_COUNT = NVL(ROLL_OVER_COUNT,0) + 1,
           EXTRACT_FLAG = 'P'
       WHERE ID = rec_alloc.xlobID;
    ELSE
       UPDATE XLOB_ALLOCATION
       SET NEXT_ROLLOVER_DATE = NEXT_ROLLOVER
       WHERE ID = rec_alloc.xlobID;
    END IF;
    
	--update audit history
	
	INSERT INTO FG_AUDIT_HISTORY (AUDIT_KEY, DATE_PERFORMED, USER_ID, USER_ROLE, ACTION, OPERATION_CODE, COMMENTS, AUDIT_SOURCE, TAM_KEY, SITE, FG_KEY)
		SELECT FG_AUDIT_KEY_SEQ.NEXTVAL, CURRENT_TIMESTAMP, 'BATCH','ADMIN','BATCH','XLOB ROLLOVER',
		'XLOB Rolloved Over for FunctionalGroup: ' || fg.name || ' and Site: ' || s.site_description,'XLOB', xalloc.ID, s.site_key,xalloc.FUNCTIONAL_GROUP_ID
		FROM XLOB_ALLOCATION xalloc, FUNCTIONAL_GROUP fg,SITE s
		WHERE xalloc.FUNCTIONAL_GROUP_ID = fg.FUNCTIONAL_GROUP_ID
		AND fg.STATUS ='ACTIVE'
		AND xalloc.SITE_KEY = s.SITE_KEY
		AND xalloc.ROLL_OVER_COUNT < MAX_ROLLOVER_COUNT
		AND xalloc.ID = rec_alloc.xlobID;

    COMMIT;

  END LOOP;
  CLOSE cur_xlob_alloc;
  COMMIT;
END;
