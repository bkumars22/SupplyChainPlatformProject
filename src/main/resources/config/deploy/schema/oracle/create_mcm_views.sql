        FROM TAM_ALLOCATION TA
          INNER JOIN FUNCTIONAL_GROUP FG
                ON FG.FUNCTIONAL_GROUP_ID = TA.FUNCTIONAL_GROUP_ID
          INNER JOIN TAM_ROLLOVER_SITE_DETAIL_PROCESSING SI
