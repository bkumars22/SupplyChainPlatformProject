/* Item AVL Extract */
CREATE OR REPLACE VIEW IV_ITEM_AVL_EXTRACT AS
SELECT
  /* MISC NICE TO HAVES */
  IAVL.SUPPLIER_PART_KEY,
  B.ITEM_KEY,
  CAST(ICA.LAST_CHANGE_DT AS TIMESTAMP) AS UPDATE_DT,
  /* ITEM ATTRIBUTES */
  B.ITEM_IDENTIFIER,  
  B.BUSINESS_ENTITY_IDENTIFIER,
  B.BUSINESS_ENTITY_TYPE_NAME,
  B.DATA_SOURCE,
  CAST(ICA.LAST_CHANGE_DT AS TIMESTAMP) AS ITEM_UPDATE_DT,
  CAST(B.INSERT_DT AS TIMESTAMP) AS ITEM_INSERT_DT,
  /* VENDOR ATTRIBUTES */
  VS.SITE_IDENTIFIER AS V_SITE_IDENTIFIER,
  IAVL.DESCRIPTION AS V_DESCRIPTION,
  VB.BUSINESS_ENTITY_IDENTIFIER AS V_BUSINESS_ENTITY_IDENTIFIER,
  VB.BUSINESS_ENTITY_TYPE_NAME AS V_BUSINESS_ENTITY_TYPE_NAME,
  VB.ITEM_IDENTIFIER AS V_ITEM_IDENTIFIER,
  VB.ITEM_UNIQUE_IDENTIFIER AS V_ITEM_UNIQUE_IDENTIFIER,  
  VB.REVISION AS V_REVISION,
  VB.VERSION AS V_VERSION,
  VC.CONTACT_NAME AS V_CONTACT_NAME,
  VC.CONTACT_UNIQUE_ID AS V_CONTACT_UNIQUE_ID,
  IAVL.PREFERRED_STATUS_CODE AS V_PREFERRED_STATUS_CODE,
  CAST(IAVL.PREFERRED_STATUS_START AS TIMESTAMP) AS V_PREFERRED_STATUS_START,
  CAST(IAVL.PREFERRED_STATUS_END AS TIMESTAMP) AS V_PREFERRED_STATUS_END,
  /* VENDOR */
  CAST(ICA.LAST_CHANGE_DT AS TIMESTAMP) AS V_UPDATE_DT,
  CAST(VB.INSERT_DT AS TIMESTAMP) AS V_INSERT_DT,
  ICA.OP_CODE
FROM
  (SELECT
   ITEM_KEY,OP_CODE,MAX(LAST_CHANGE_DT) LAST_CHANGE_DT
   FROM ITEM_CHANGE_AUDIT
   GROUP BY ITEM_KEY,OP_CODE) ICA
  INNER JOIN IV_ITEM_BUSINESS B ON
    B.ITEM_KEY = ICA.ITEM_KEY
  LEFT OUTER JOIN ITEM_AVL IAVL ON
    IAVL.ITEM_KEY = ICA.ITEM_KEY
  LEFT OUTER JOIN IV_ITEM_BUSINESS VB ON
    IAVL.SUPPLIER_PART_KEY = VB.ITEM_KEY
  LEFT OUTER JOIN PCM_ITEM_AVL_SITE IAS ON
    IAS.AVL_KEY = IAVL.AVL_KEY
  LEFT OUTER JOIN SITE VS ON
    IAS.SITE_KEY = VS.SITE_KEY
  LEFT OUTER JOIN CONTACT VC ON
    VB.CONTACT_KEY = VC.CONTACT_KEY;

