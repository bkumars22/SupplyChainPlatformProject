CREATE OR REPLACE PROCEDURE check_child_rows (
    p_parent_table   IN VARCHAR2,
    p_parent_column  IN VARCHAR2,
    p_parent_value   IN VARCHAR2,
    p_result         OUT VARCHAR2
)
AS
    v_parent_owner    VARCHAR2(50);
    v_child_owner     VARCHAR2(50);
    v_child_table     VARCHAR2(50);
    v_child_column    VARCHAR2(50);
    v_sql             VARCHAR2(1000);
    v_count           NUMBER;
    v_msg             VARCHAR2(4000) := '';
    v_has_child_rows  BOOLEAN := FALSE;

    CURSOR fk_cursor IS
        SELECT
            c.owner AS child_owner,
            c.table_name AS child_table,
            cc.column_name AS child_column
        FROM all_constraints c
        JOIN all_cons_columns cc
            ON c.owner = cc.owner AND c.constraint_name = cc.constraint_name
        WHERE c.constraint_type = 'R'
           AND (
                    -- Exclude tables
                    c.table_name <> 'ITEM_ADD_ATTRIBUTE'
                    -- Exclude ITEM_ITEM_CATEGORY only when parent table is ITEM_ITEM_CATEGORY
                    AND (UPPER(p_parent_table) <> 'ITEM_ITEM_CATEGORY' OR c.table_name <> 'ITEM_ITEM_CATEGORY')
              )
          AND c.r_constraint_name = (
                SELECT constraint_name
                FROM all_constraints
                WHERE table_name = UPPER(p_parent_table)
                  AND constraint_type = 'P'
                  AND ROWNUM = 1
            );
BEGIN
    -- Get parent table owner
    SELECT owner INTO v_parent_owner
    FROM all_tables
    WHERE table_name = UPPER(p_parent_table)
      AND ROWNUM = 1;

    -- Loop through referencing child tables (excluding ITEM_ITEM_CATEGORY)
    FOR fk IN fk_cursor LOOP
        v_child_owner := fk.child_owner;
        v_child_table := fk.child_table;
        v_child_column := fk.child_column;

        v_sql := 'SELECT COUNT(*) FROM "' || v_child_owner || '"."' || v_child_table ||
                 '" WHERE "' || v_child_column || '" = :1';

        EXECUTE IMMEDIATE v_sql INTO v_count USING p_parent_value;

        IF v_count > 0 THEN
            IF NOT v_has_child_rows THEN
                v_msg := 'Child rows found in: ';
                v_has_child_rows := TRUE;
            END IF;

            v_msg := v_msg || v_child_owner || '.' || v_child_table ||
                     ' (' || v_count || ' rows); ';
        END IF;
    END LOOP;

    IF v_has_child_rows THEN
        p_result := v_msg;
    ELSE
        p_result := 'No child rows found.';
    END IF;
END;
