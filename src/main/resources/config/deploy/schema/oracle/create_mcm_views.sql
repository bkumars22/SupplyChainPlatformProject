                AND ITM.EOL = 'Y'
                AND ITM.EOL_TYPE IN (SELECT FORECAST_KEY
                                       FROM forecasts_to_close
                                      WHERE RTYPE = 'EOL_TYPE')
          LEFT JOIN item_fg_map FCGALL
             ON ITM.ITEM_KEY = FCGALL.ITEM_KEY
