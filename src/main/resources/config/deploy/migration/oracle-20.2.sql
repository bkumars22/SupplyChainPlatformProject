    CASE WHEN ITEM_ALLOCATION IS NULL THEN
        CASE WHEN ITEM_IDENTIFIER = DEFAULT_ITEM_IDENTIFIER THEN
            CASE WHEN SUM(ITEM_ALLOCATION) over (PARTITION BY TAM_ALLOCATION_ID,TAM_SUPPLIER_ALLOCATION_ID) is null THEN 100
            ELSE 0 END
        ELSE 0 END
    ELSE ITEM_ALLOCATION END AS ITEM_ALLOCATION,ITEM_IDENTIFIER,SUPPLIER_SUM_ALLOCATION,SITE_KEY
