                       AND forecast_model = FC_MODEL
                       AND status = FC_STATUS)
         LOOP
            v_output := '[' || r.forecast_key || ']' || v_output;

            INSERT INTO logger
                 VALUES (
                           SYSDATE,
                              ' v_output :'
                           || v_output
                           || '--->'
                           || r.forecast_key);

            INSERT INTO forecasts_to_close (stat_date, forecast_key, RTYPE)
                 VALUES (SYSDATE, r.forecast_key, 'RESULT');
         END LOOP;

         result := -1;
      END IF;

      -----------------------------------
