               INSERT INTO logger
                    VALUES (
                              SYSDATE,
                                 'v_count:'
                              || v_count
                              || ' tot_count: '
                              || tot_count);

               tot_count := v_count + tot_count;

               IF tot_count = 0
               THEN
                  result := 0;
               ELSE
                  result := tot_count;
               END IF;


               INSERT INTO logger
                    VALUES (SYSDATE, 'Since v_count=0 :' || result);
            ELSE
               INSERT INTO logger
                    VALUES (SYSDATE, 'entered this case of exit');

               result := -1;
               EXIT;
            END IF;
         END LOOP;
      ELSE
         INSERT INTO logger
              VALUES (
                        SYSDATE,
                        ' Funtional Group ID is NULL:'
                        || c1.functional_group_id);

         FOR r
            IN (SELECT forecast_key
                  FROM pcm_forecast
