        CASE WHEN PERIOD_SUM_ALOC IS NULL THEN GLOBAL_ALLOCATION
        ELSE SUPPLIER_ALLOCATION
        END AS SUPPLIER_ALLOCATION,ITEM_IDENTIFIER,DATA_SOURCE,TAM_SUPPLIER_ALLOCATION_ID,
        CASE WHEN PERIOD_ITEM_ALLOCATION IS NULL THEN GLOBAL_ITEM_ALLOCATION
        ELSE ITEM_ALLOCATION
        END AS ITEM_ALLOCATION FROM (
