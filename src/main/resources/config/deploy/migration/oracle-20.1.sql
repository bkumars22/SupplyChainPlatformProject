CREATE OR REPLACE PROCEDURE SITE_CHANGE_INSERT_PROC (NEW_SITE_KEY IN NUMBER,NEW_SITE_DETAIL_ID IN NUMBER,OLD_SITE_DETAIL_ID IN NUMBER,NEW_SITE_TYPE IN VARCHAR2,OLD_TAM_PROCESSING_FLAG IN VARCHAR2,
  NEW_TAM_PROCESSING_FLAG IN VARCHAR2,OPERATION_TYPE IN VARCHAR2,TARGET IN VARCHAR2)
AS
PRAGMA AUTONOMOUS_TRANSACTION;

v_SITE_TYPE VARCHAR2(255);
v_SITE_KEY NUMBER;

BEGIN
  IF (TARGET = 'SITE') THEN
    IF (OPERATION_TYPE = 'INSERT') THEN
      IF (NEW_SITE_TYPE = 'REGION') THEN
        INSERT INTO SITE_CHANGE_DATA
        (SITE_KEY,SITE_TYPE,CREATED_ON)
        SELECT s.SITE_KEY,s.SITE_KEY,SYSTIMESTAMP FROM SITE s WHERE s.PARENT_SITE_KEY = NEW_SITE_KEY;
      ELSIF (NEW_SITE_TYPE = 'SITE') THEN
        INSERT INTO SITE_CHANGE_DATA
        (SITE_KEY,SITE_TYPE,CREATED_ON) VALUES (NEW_SITE_KEY,NEW_SITE_TYPE,SYSTIMESTAMP);
      END IF;
    ELSIF (OPERATION_TYPE = 'UPDATE') THEN
      IF (OLD_SITE_DETAIL_ID IS NULL AND NEW_SITE_DETAIL_ID IS NOT NULL) THEN
        IF (NEW_SITE_TYPE = 'REGION') THEN
          INSERT INTO SITE_CHANGE_DATA
          (SITE_KEY,SITE_TYPE,CREATED_ON)
          SELECT s.SITE_KEY,s.SITE_TYPE,SYSTIMESTAMP FROM SITE s WHERE s.PARENT_SITE_KEY = NEW_SITE_KEY;
        ELSIF (NEW_SITE_TYPE = 'SITE') THEN
          INSERT INTO SITE_CHANGE_DATA (SITE_KEY,SITE_TYPE,CREATED_ON) VALUES (NEW_SITE_KEY,NEW_SITE_TYPE,SYSTIMESTAMP);
        END IF;
      END IF;
    END IF;
  ELSIF (TARGET = 'SITE_DETAILS') THEN
    IF ((OLD_TAM_PROCESSING_FLAG IS NULL OR OLD_TAM_PROCESSING_FLAG = '0' ) AND NEW_TAM_PROCESSING_FLAG = '1') THEN
    
    SELECT s.SITE_TYPE,s.SITE_KEY INTO v_SITE_TYPE,v_SITE_KEY FROM SITE s WHERE s.SITE_DETAIL_ID = NEW_SITE_DETAIL_ID AND ROWNUM = 1;
  
      IF (v_SITE_TYPE = 'REGION') THEN
        INSERT INTO SITE_CHANGE_DATA
          (SITE_KEY,SITE_TYPE,CREATED_ON)
          SELECT s.SITE_KEY,s.SITE_KEY,SYSTIMESTAMP FROM SITE s WHERE s.PARENT_SITE_KEY = v_SITE_KEY;
      ELSIF (v_SITE_TYPE = 'SITE') THEN
        INSERT INTO SITE_CHANGE_DATA (SITE_KEY,SITE_TYPE,CREATED_ON) VALUES (v_SITE_KEY,v_SITE_TYPE,SYSTIMESTAMP);
      END IF;
    END IF;
  END IF;
COMMIT;
END;
