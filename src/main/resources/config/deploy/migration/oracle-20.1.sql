create or replace TRIGGER T_TAM_EXTRACT_SITE_CHANGE
	AFTER INSERT OR UPDATE ON SITE
	FOR EACH ROW

DECLARE
      v_newSiteKey          SITE.SITE_KEY%TYPE;
      v_newSiteDetailId     SITE.SITE_DETAIL_ID%TYPE;
      v_oldSiteDetailId     SITE.SITE_DETAIL_ID%TYPE;
      v_newSiteType         SITE.SITE_TYPE%TYPE;
BEGIN
   v_newSiteKey        := :new.SITE_KEY;
   v_newSiteDetailId   := :new.SITE_DETAIL_ID;
   v_oldSiteDetailId   := :old.SITE_DETAIL_ID;
   v_newSiteType       := :new.SITE_TYPE;

	IF INSERTING THEN
    SITE_CHANGE_INSERT_PROC(v_newSiteKey,v_newSiteDetailId,v_oldSiteDetailId,v_newSiteType,null,null,'INSERT','SITE');
  END IF;
  
  IF UPDATING THEN 
    SITE_CHANGE_INSERT_PROC(v_newSiteKey,v_newSiteDetailId,v_oldSiteDetailId,v_newSiteType,null,null,'UPDATE','SITE');
  END IF;
END;
