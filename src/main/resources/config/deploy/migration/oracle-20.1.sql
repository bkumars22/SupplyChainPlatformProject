create or replace PROCEDURE SITE_CHANGE_TAM_CASCADE_EXTRACT_PROC (vOUT_RESULT out SYS_REFCURSOR,V_START_DATE DATE)
AS
  CURSOR cur_FgSite
  IS
  WITH a1 AS
    (SELECT tam.FUNCTIONAL_GROUP_ID,site.SITE_KEY,site.SITE_DESCRIPTION,
    CASE site.SITE_TYPE WHEN 'GLOBAL'  THEN 1
                        WHEN 'REGION' THEN 2
                        END AS SITE_TYPE
    FROM TAM_ALLOCATION tam LEFT JOIN SITE site
    ON site.SITE_KEY = tam.SITE_KEY AND site.SITE_TYPE IN('REGION','GLOBAL') WHERE site.SITE_KEY is not null),a2 AS(SELECT FUNCTIONAL_GROUP_ID,SITE_KEY,MAX(SITE_TYPE) over (partition BY FUNCTIONAL_GROUP_ID) max_site FROM a1),a3 AS
    (SELECT FUNCTIONAL_GROUP_ID,MAX(SITE_KEY) AS SITE_KEY,max_site FROM a2 GROUP BY FUNCTIONAL_GROUP_ID,max_site) 
    SELECT a3.FUNCTIONAL_GROUP_ID,CASE WHEN exists (select 1 from tam_allocation where FUNCTIONAL_GROUP_ID=a3.FUNCTIONAL_GROUP_ID and site_key = site.PARENT_SITE_KEY) THEN site.PARENT_SITE_KEY ELSE 1 END AS SITE_KEY,CASE max_site WHEN 1 THEN 'GLOBAL' WHEN 2 THEN 'REGION' END AS SITE_TYPE,sc.SITE_KEY AS NEW_SITE_KEY,site.SITE_DESCRIPTION AS NEW_SITE_DESCRIPTION,
    site.SITE_TYPE AS NEW_SITE_TYPE FROM a3,SITE_CHANGE_DATA sc 
    LEFT JOIN SITE site ON site.SITE_KEY = sc.SITE_KEY
    LEFT JOIN SITE_DETAILS sideDetails ON sideDetails.ID = site.SITE_DETAIL_ID
    LEFT JOIN BUSINESS_ENTITY be ON site.BUSINESS_ENTITY_KEY = be.BUSINESS_ENTITY_KEY
    LEFT JOIN BUSINESS_ENTITY_TYPE bet ON be.BUSINESS_ENTITY_TYPE_KEY        = bet.BUSINESS_ENTITY_TYPE_KEY
    WHERE sideDetails.TAM_PROCESSING_FLAG =1
    AND bet.BUSINESS_ENTITY_TYPE_NAME     = 'ENTERPRISE';

rec_FgSite cur_FgSite%ROWTYPE;

V_ActualTamExists NUMBER(1);

BEGIN
EXECUTE IMMEDIATE 'TRUNCATE TABLE SITE_CHANGE_TAM_CASCADE';
DELETE FROM SITE_CHANGE_DATA WHERE RowID NOT IN (SELECT MIN(RowID) FROM SITE_CHANGE_DATA GROUP BY SITE_KEY,SITE_TYPE);
  OPEN cur_FgSite;
  LOOP
    FETCH cur_FgSite INTO rec_FgSite;
    EXIT
  WHEN cur_FgSite%NOTFOUND;
    BEGIN
      SELECT 1
      INTO V_ActualTamExists
      FROM DUAL
      WHERE EXISTS
        (SELECT 1
        FROM TAM_ALLOCATION tam
        WHERE tam.FUNCTIONAL_GROUP_ID = rec_FgSite.FUNCTIONAL_GROUP_ID
        AND tam.SITE_KEY              = rec_FgSite.NEW_SITE_KEY
        );
    EXCEPTION
    WHEN NO_DATA_FOUND THEN
      V_ActualTamExists := 0;
    END;
  IF (V_ActualTamExists = 1) THEN
    
    INSERT INTO SITE_CHANGE_TAM_CASCADE (TAM_ALLOCATION_ID,FUNCTIONAL_GROUP_ID,FG_NAME,LAST_CHANGED_BY,LAST_CHANGED_ON,CREATED_BY,CREATED_ON,SITE_KEY,SITE_DESCRIPTION,SITE_TYPE,SUPPLIER_IDENTIFIER, 
    SUPPLIER_NAME,START_DATE,END_DATE,TAM_SUPPLIER_ALLOCATION_ID,SUPPLIER_ALLOCATION,TOT_SUPP_ALOC,TAM_ITEM_ALLOCATION_ID,ITEM_ALLOCATION,ITEM_IDENTIFIER)
      SELECT TAM_ALLOCATION_ID,FUNCTIONAL_GROUP_ID,FG_NAME,LAST_CHANGED_BY,LAST_CHANGED_ON,CREATED_BY,CREATED_ON,SITE_KEY,rec_FgSite.NEW_SITE_DESCRIPTION,rec_FgSite.NEW_SITE_TYPE,SUPPLIER_IDENTIFIER,
      SUPPLIER,START_DATE,END_DATE,FUNCTIONAL_GROUP_ID||'-'||SITE_KEY||'-'||SUPPLIER_IDENTIFIER,SUPPLIER_ALLOCATION,TOTAL_SUPPLIER_ALLOCATION,FUNCTIONAL_GROUP_ID||'-'||SITE_KEY||'-'||SUPPLIER_IDENTIFIER||'-'||ITEM_IDENTIFIER,ITEM_ALLOCATION,ITEM_IDENTIFIER 
      FROM (
      SELECT TAM_ALLOCATION_ID,FUNCTIONAL_GROUP_ID,FG_NAME,SITE_KEY,LAST_CHANGED_BY,LAST_CHANGED_ON,CREATED_BY,CREATED_ON,SUPPLIER_IDENTIFIER,SUPPLIER,START_DATE,END_DATE,SUPPLIER_ALLOCATION,
         SUM(CASE WHEN SUPP_ROW_NUM = 1 THEN SUPPLIER_ALLOCATION ELSE NULL END) OVER (PARTITION BY FUNCTIONAL_GROUP_ID,SITE_KEY,START_DATE) AS TOTAL_SUPPLIER_ALLOCATION,
        SUM(SUPPLIER_ALLOCATION) OVER (PARTITION BY FUNCTIONAL_GROUP_ID,SITE_KEY,SUPPLIER_IDENTIFIER) AS SUPPLIER_SUM_ALLOCATION,ITEM_IDENTIFIER,
		CASE WHEN ITEM_ALLOCATION IS NULL THEN
            CASE WHEN ITEM_IDENTIFIER = DEFAULT_ITEM_IDENTIFIER THEN
                CASE WHEN SUM(ITEM_ALLOCATION) over (PARTITION BY TAM_ALLOCATION_ID,TAM_SUPPLIER_ALLOCATION_ID) is null THEN 100
                ELSE 0 END
            ELSE 0 END
        ELSE ITEM_ALLOCATION END AS ITEM_ALLOCATION
        FROM(
          SELECT TAM_ALLOCATION_ID,FUNCTIONAL_GROUP_ID,FG_NAME,LAST_CHANGED_BY,LAST_CHANGED_ON,CREATED_BY,CREATED_ON,SITE_KEY,SUPPLIER_IDENTIFIER,SUPPLIER,START_DATE,END_DATE,
          	ROW_NUMBER() OVER (PARTITION BY FUNCTIONAL_GROUP_ID,SITE_KEY,SUPPLIER_IDENTIFIER,START_DATE order by ITEM_IDENTIFIER ) AS SUPP_ROW_NUM,
            CASE WHEN PERIOD_SUM_ALOC IS NULL THEN
            CASE WHEN REGION_PERIOD_SUM IS NULL THEN GLOBAL_ALLOCATION ELSE REGION_ALLOCATION END
            ELSE SUPPLIER_ALLOCATION
            END AS SUPPLIER_ALLOCATION,ITEM_IDENTIFIER,
 			CASE WHEN PERIOD_ITEM_ALLOCATION IS NULL THEN
            CASE WHEN REGION_PERIOD_ITEM_SUM IS NULL THEN GLOBAL_ITEM_ALLOCATION ELSE REGION_ITEM_ALLOCATION END
            ELSE ITEM_ALLOCATION
            END AS ITEM_ALLOCATION,
            CASE  WHEN (COUNT(CASE WHEN DATA_SOURCE = 'EMC' THEN 1 END) OVER (PARTITION BY FUNCTIONAL_GROUP_ID,SITE_KEY,SUPPLIER_IDENTIFIER,START_DATE)) > 0
            THEN MAX(ITEM_IDENTIFIER) OVER (PARTITION BY FUNCTIONAL_GROUP_ID,SITE_KEY,SUPPLIER_IDENTIFIER,START_DATE)
            ELSE MIN(ITEM_IDENTIFIER) OVER (PARTITION BY FUNCTIONAL_GROUP_ID,SITE_KEY,SUPPLIER_IDENTIFIER,START_DATE)
            END AS DEFAULT_ITEM_IDENTIFIER,TAM_SUPPLIER_ALLOCATION_ID 
            FROM (
              SELECT x1.*,
                CASE WHEN x1.REGION_TAM IS NULL THEN NULL ELSE (SELECT tsa2.ALLOCATION FROM TAM_SUPPLIER_ALLOCATION tsa2 WHERE tsa2.TAM_ALLOCATION_ID = x1.REGION_TAM AND tsa2.START_DATE = x1.START_DATE AND tsa2.BUSINESS_ENTITY_KEY = x1.SUPPLIER_IDENTIFIER) END AS REGION_ALLOCATION,
                CASE WHEN x1.REGION_TAM IS NULL THEN NULL ELSE (SELECT tia2.ALLOCATION FROM TAM_ITEM_ALLOCATION tia2 INNER JOIN TAM_SUPPLIER_ALLOCATION tsa2 ON tsa2.TAM_SUPPLIER_ALLOCATION_ID = tia2.TAM_SUPPLIER_ALLOCATION_ID WHERE tsa2.TAM_ALLOCATION_ID = x1.REGION_TAM AND tsa2.START_DATE = x1.START_DATE AND tsa2.BUSINESS_ENTITY_KEY = x1.SUPPLIER_IDENTIFIER AND tia2.ITEM_KEY = x1.ITEM_KEY) END AS REGION_ITEM_ALLOCATION,
                CASE WHEN x1.REGION_TAM IS NULL THEN NULL ELSE (SELECT SUM(tsa2.ALLOCATION) FROM TAM_SUPPLIER_ALLOCATION tsa2 WHERE tsa2.TAM_ALLOCATION_ID = x1.REGION_TAM AND tsa2.START_DATE = x1.START_DATE) END AS REGION_PERIOD_SUM,
                CASE WHEN x1.REGION_TAM IS NULL THEN NULL ELSE (SELECT SUM(tia2.ALLOCATION) FROM TAM_ITEM_ALLOCATION tia2 INNER JOIN TAM_SUPPLIER_ALLOCATION tsa2 ON tsa2.TAM_SUPPLIER_ALLOCATION_ID = tia2.TAM_SUPPLIER_ALLOCATION_ID WHERE tsa2.TAM_ALLOCATION_ID = x1.REGION_TAM AND tsa2.START_DATE = x1.START_DATE) END AS REGION_PERIOD_ITEM_SUM,
                CASE WHEN x1.GLOBAL_TAM IS NULL THEN NULL ELSE (SELECT tsa2.ALLOCATION FROM TAM_SUPPLIER_ALLOCATION tsa2 WHERE tsa2.TAM_ALLOCATION_ID = x1.GLOBAL_TAM AND tsa2.START_DATE = x1.START_DATE AND tsa2.BUSINESS_ENTITY_KEY = x1.SUPPLIER_IDENTIFIER) END AS GLOBAL_ALLOCATION,
                CASE WHEN x1.GLOBAL_TAM IS NULL THEN NULL ELSE (SELECT tia2.ALLOCATION FROM TAM_ITEM_ALLOCATION tia2 INNER JOIN TAM_SUPPLIER_ALLOCATION tsa2 ON tsa2.TAM_SUPPLIER_ALLOCATION_ID = tia2.TAM_SUPPLIER_ALLOCATION_ID WHERE tsa2.TAM_ALLOCATION_ID = x1.GLOBAL_TAM AND tsa2.START_DATE = x1.START_DATE AND tsa2.BUSINESS_ENTITY_KEY = x1.SUPPLIER_IDENTIFIER AND tia2.ITEM_KEY = x1.ITEM_KEY) END AS GLOBAL_ITEM_ALLOCATION
                FROM(
                  SELECT TAM_ALLOCATION_ID,FUNCTIONAL_GROUP_ID,FG_NAME,LAST_CHANGED_BY,LAST_CHANGED_ON,CREATED_BY,CREATED_ON,SITE_KEY,SUPPLIER_IDENTIFIER,SUPPLIER,START_DATE,END_DATE,
                  SUPPLIER_ALLOCATION,ITEM_IDENTIFIER,ITEM_ALLOCATION,SUM(ITEM_ALLOCATION) OVER (PARTITION BY TAM_ALLOCATION_ID,START_DATE) PERIOD_ITEM_ALLOCATION,SUM(SUPPLIER_ALLOCATION) OVER (PARTITION BY TAM_ALLOCATION_ID,START_DATE) PERIOD_SUM_ALOC,ITEM_KEY,TAM_SUPPLIER_ALLOCATION_ID,
                  (SELECT tam1.TAM_ALLOCATION_ID FROM TAM_ALLOCATION tam1 WHERE tam1.FUNCTIONAL_GROUP_ID = x.FUNCTIONAL_GROUP_ID AND tam1.SITE_KEY = (SELECT PARENT_SITE_KEY FROM SITE WHERE SITE_KEY = x.SITE_KEY)) AS REGION_TAM,
                  (SELECT tam1.TAM_ALLOCATION_ID FROM TAM_ALLOCATION tam1 WHERE tam1.FUNCTIONAL_GROUP_ID = x.FUNCTIONAL_GROUP_ID AND tam1.SITE_KEY = 1) AS GLOBAL_TAM,DATA_SOURCE
                  FROM (
                    SELECT ta.TAM_ALLOCATION_ID,ta.FUNCTIONAL_GROUP_ID,fg.NAME AS FG_NAME,ta.LAST_CHANGED_BY,ta.LAST_CHANGED_ON,ta.CREATED_BY,ta.CREATED_ON,ta.SITE_KEY,tsa.BUSINESS_ENTITY_KEY AS SUPPLIER_IDENTIFIER,
                    be.BUSINESS_ENTITY_NAME AS SUPPLIER,tsa.START_DATE,tsa.END_DATE,tsa.ALLOCATION AS SUPPLIER_ALLOCATION,im.ITEM_IDENTIFIER AS ITEM_IDENTIFIER,tia.ALLOCATION AS ITEM_ALLOCATION,tsa.TAM_SUPPLIER_ALLOCATION_ID AS TAM_SUPPLIER_ALLOCATION_ID,tia.ITEM_KEY AS ITEM_KEY,im.DATA_SOURCE AS DATA_SOURCE FROM TAM_ALLOCATION ta
                    LEFT JOIN TAM_SUPPLIER_ALLOCATION tsa  ON tsa.TAM_ALLOCATION_ID = ta.TAM_ALLOCATION_ID
                    LEFT JOIN TAM_ITEM_ALLOCATION tia ON tsa.TAM_SUPPLIER_ALLOCATION_ID = tia.TAM_SUPPLIER_ALLOCATION_ID
                    LEFT JOIN FUNCTIONAL_GROUP fg ON fg.FUNCTIONAL_GROUP_ID = ta.FUNCTIONAL_GROUP_ID
                    LEFT JOIN ITEM_MASTER im on tia.ITEM_KEY = im.ITEM_KEY
                    INNER JOIN SITE s ON ta.SITE_KEY = s.SITE_KEY
                    INNER JOIN BUSINESS_ENTITY be ON be.BUSINESS_ENTITY_KEY = tsa.BUSINESS_ENTITY_KEY
                    WHERE tsa.START_DATE >= V_START_DATE
                    AND ta.FUNCTIONAL_GROUP_ID = rec_FgSite.FUNCTIONAL_GROUP_ID  AND s.SITE_KEY = rec_FgSite.NEW_SITE_KEY)x 
                  ) x1 
                ) x2
              ) x3
          ) x4  WHERE x4.SUPPLIER_SUM_ALLOCATION > 0 AND x4.ITEM_ALLOCATION > 0;

  ELSIF (V_ActualTamExists = 0 AND rec_FgSite.SITE_TYPE = 'REGION') THEN
    
    INSERT INTO SITE_CHANGE_TAM_CASCADE (TAM_ALLOCATION_ID,FUNCTIONAL_GROUP_ID,FG_NAME,LAST_CHANGED_BY,LAST_CHANGED_ON,CREATED_BY,CREATED_ON,SITE_KEY,SITE_DESCRIPTION,SITE_TYPE,SUPPLIER_IDENTIFIER, 
    SUPPLIER_NAME,START_DATE,END_DATE,TAM_SUPPLIER_ALLOCATION_ID,SUPPLIER_ALLOCATION,TOT_SUPP_ALOC,TAM_ITEM_ALLOCATION_ID,ITEM_ALLOCATION,ITEM_IDENTIFIER)
    SELECT TAM_ALLOCATION_ID,FUNCTIONAL_GROUP_ID,FG_NAME,LAST_CHANGED_BY,LAST_CHANGED_ON,CREATED_BY,CREATED_ON,rec_FgSite.NEW_SITE_KEY,rec_FgSite.NEW_SITE_DESCRIPTION,rec_FgSite.NEW_SITE_TYPE,SUPPLIER_IDENTIFIER,
    SUPPLIER,START_DATE,END_DATE,FUNCTIONAL_GROUP_ID||'-'||SITE_KEY||'-'||SUPPLIER_IDENTIFIER,SUPPLIER_ALLOCATION,TOTAL_SUPPLIER_ALLOCATION,FUNCTIONAL_GROUP_ID||'-'||SITE_KEY||'-'||SUPPLIER_IDENTIFIER||'-'||ITEM_IDENTIFIER,ITEM_ALLOCATION,ITEM_IDENTIFIER
	FROM (
    SELECT TAM_ALLOCATION_ID,FUNCTIONAL_GROUP_ID,FG_NAME,LAST_CHANGED_BY,LAST_CHANGED_ON,CREATED_BY,CREATED_ON,rec_FgSite.NEW_SITE_KEY,rec_FgSite.NEW_SITE_DESCRIPTION,rec_FgSite.NEW_SITE_TYPE,SUPPLIER_IDENTIFIER,
    SUPPLIER,START_DATE,END_DATE,FUNCTIONAL_GROUP_ID||'-'||SITE_KEY||'-'||SUPPLIER_IDENTIFIER,SUPPLIER_ALLOCATION,TOTAL_SUPPLIER_ALLOCATION,FUNCTIONAL_GROUP_ID||'-'||SITE_KEY||'-'||SUPPLIER_IDENTIFIER||'-'||ITEM_IDENTIFIER,
    CASE WHEN ITEM_ALLOCATION IS NULL THEN
        CASE WHEN ITEM_IDENTIFIER = DEFAULT_ITEM_IDENTIFIER THEN
            CASE WHEN SUM(ITEM_ALLOCATION) over (PARTITION BY TAM_ALLOCATION_ID,TAM_SUPPLIER_ALLOCATION_ID) is null THEN 100
            ELSE 0 END
        ELSE 0 END
    ELSE ITEM_ALLOCATION END AS ITEM_ALLOCATION,ITEM_IDENTIFIER,SUPPLIER_SUM_ALLOCATION,SITE_KEY
    FROM (
      SELECT TAM_ALLOCATION_ID,FUNCTIONAL_GROUP_ID,FG_NAME,SITE_KEY,LAST_CHANGED_BY,LAST_CHANGED_ON,CREATED_BY,CREATED_ON,SUPPLIER_IDENTIFIER,SUPPLIER,START_DATE,END_DATE,SUPPLIER_ALLOCATION,
      SUM(CASE WHEN SUPP_ROW_NUM = 1 THEN SUPPLIER_ALLOCATION ELSE NULL END) OVER (PARTITION BY FUNCTIONAL_GROUP_ID,SITE_KEY,START_DATE) AS TOTAL_SUPPLIER_ALLOCATION,
      SUM(SUPPLIER_ALLOCATION) OVER (PARTITION BY FUNCTIONAL_GROUP_ID,SITE_KEY,SUPPLIER_IDENTIFIER) AS SUPPLIER_SUM_ALLOCATION,ITEM_IDENTIFIER,ITEM_ALLOCATION,
      CASE  WHEN (COUNT(CASE WHEN DATA_SOURCE = 'EMC' THEN 1 END) OVER (PARTITION BY FUNCTIONAL_GROUP_ID,SITE_KEY,SUPPLIER_IDENTIFIER,START_DATE)) > 0
      THEN MAX(ITEM_IDENTIFIER) OVER (PARTITION BY FUNCTIONAL_GROUP_ID,SITE_KEY,SUPPLIER_IDENTIFIER,START_DATE)
      ELSE MIN(ITEM_IDENTIFIER) OVER (PARTITION BY FUNCTIONAL_GROUP_ID,SITE_KEY,SUPPLIER_IDENTIFIER,START_DATE)
