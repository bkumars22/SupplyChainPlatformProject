CREATE OR REPLACE PROCEDURE ITEM_CHANGE_INSERT_PROC (ITEM_KEY_PARAM IN NUMBER)
AS
PRAGMA AUTONOMOUS_TRANSACTION;

BEGIN
   INSERT INTO ITEM_MASTER_EXTRACT (ITEM_KEY,LAST_CHANGE_DT) SELECT ITEM_KEY_PARAM,SYSDATE from dual
    where not exists(SELECT 1 FROM ITEM_MASTER_EXTRACT WHERE ITEM_KEY = ITEM_KEY_PARAM);
COMMIT;
END;
