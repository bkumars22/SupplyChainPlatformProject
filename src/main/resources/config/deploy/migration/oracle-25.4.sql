	            ) x
	         )x
	       )
	     )
	    )
	  ) WHERE DISCP_ROLLOVER_EXTRACT_FLAG = NVL(vEXTRACT_FLAG,DISCP_ROLLOVER_EXTRACT_FLAG)
    ) WHERE SUPP_ALLOC_NOT_NULL > 0 AND ITEM_ALLOC_NOT_NULL > 0;
  COMMIT;

	DBMS_STATS.GATHER_TABLE_STATS(OWNNAME=>USER,TABNAME=>'TAM_ROLLOVER_ALLOC_CASCADE_PROC_STG2',CASCADE => TRUE, DEGREE=>16);

