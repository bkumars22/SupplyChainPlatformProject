		vOUT_RESULT out SYS_REFCURSOR
	) AS
	vMONTH_START_DATE DATE;
	vWEEK_START_DATE DATE;
	BEGIN

	SELECT TO_DATE(NEXT_DAY(SYSDATE,'SATURDAY') - 7) INTO vWEEK_START_DATE FROM DUAL;

	SELECT MIN(FISCAL_PERIOD_START_DATE)  INTO vMONTH_START_DATE
	 FROM fiscal_period
	WHERE FISCAL_PERIOD_TYPE IN ('M','W')
	AND FISCAL_PERIOD_START_DATE >= trunc(vWEEK_START_DATE);

	    -- Update TAM_ALLOCATION to set the DISCP_ROLLOVER_EXTRACT_FLAG to Y for DELTA Extractions --
	  UPDATE TAM_ALLOCATION TA SET DISCP_ROLLOVER_EXTRACT_FLAG = 'Y'
	      WHERE DISCP_ROLLOVER_EXTRACT_FLAG = 'P'
	      AND TAM_ALLOCATION_ID IN
	      (
	        SELECT  TAM_ALLOCATION_ID FROM TAM_ROLLOVER_ALLOC_CASCADE_PROC_STG2 TAS WHERE DISCP_ROLLOVER_EXTRACT_FLAG = 'P'
	      );

	      COMMIT;

	  OPEN VOUT_RESULT FOR
			SELECT 1 AS COUNT FROM DUAL;

		EXCEPTION
			WHEN OTHERS THEN
				RAISE;
	END TAM_ALLOC_ROLLOVER_CASCADE_DELTA_UPDATE;

