	        select TAM_ALLOCATION_ID, FUNCTIONAL_GROUP_ID, FG_NAME, LAST_CHANGED_BY, LAST_CHANGED_ON, ALLOW_HEDGING, CREATED_BY, CREATED_ON, DISCP_ROLLOVER_EXTRACT_FLAG, SITE_KEY, SITE_IDENTIFIER, SITE_DESCRIPTION,
