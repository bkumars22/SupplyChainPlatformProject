CREATE OR REPLACE PROCEDURE check_child_rows (
    p_parent_table   IN VARCHAR2,
    p_parent_column  IN VARCHAR2,
    p_parent_value   IN VARCHAR2,
    p_result         OUT VARCHAR2
)
AS
    v_parent_owner    VARCHAR2(50);
    v_child_owner     VARCHAR2(50);
    v_child_table     VARCHAR2(50);
    v_child_column    VARCHAR2(50);
    v_sql             VARCHAR2(1000);
    v_count           NUMBER;
    v_msg             VARCHAR2(4000) := '';
    v_has_child_rows  BOOLEAN := FALSE;

    CURSOR fk_cursor IS
        SELECT
            c.owner AS child_owner,
            c.table_name AS child_table,
            cc.column_name AS child_column
        FROM all_constraints c
        JOIN all_cons_columns cc
            ON c.owner = cc.owner AND c.constraint_name = cc.constraint_name
        WHERE c.constraint_type = 'R'
          AND (
                       -- Exclude tables
                       c.table_name <> 'ITEM_ADD_ATTRIBUTE'
                       -- Exclude ITEM_ITEM_CATEGORY only when parent table is ITEM_ITEM_CATEGORY
                       AND (UPPER(p_parent_table) <> 'ITEM_ITEM_CATEGORY' OR c.table_name <> 'ITEM_ITEM_CATEGORY')
               )
          AND c.r_constraint_name = (
                SELECT constraint_name
                FROM all_constraints
                WHERE table_name = UPPER(p_parent_table)
                  AND constraint_type = 'P'
                  AND ROWNUM = 1
            );
BEGIN
    -- Get parent table owner
    SELECT owner INTO v_parent_owner
    FROM all_tables
    WHERE table_name = UPPER(p_parent_table)
      AND ROWNUM = 1;

    -- Loop through referencing child tables (excluding ITEM_ITEM_CATEGORY)
    FOR fk IN fk_cursor LOOP
        v_child_owner := fk.child_owner;
        v_child_table := fk.child_table;
        v_child_column := fk.child_column;

        v_sql := 'SELECT COUNT(*) FROM "' || v_child_owner || '"."' || v_child_table ||
                 '" WHERE "' || v_child_column || '" = :1';

        EXECUTE IMMEDIATE v_sql INTO v_count USING p_parent_value;

        IF v_count > 0 THEN
            IF NOT v_has_child_rows THEN
                v_msg := 'Child rows found in: ';
                v_has_child_rows := TRUE;
            END IF;

            v_msg := v_msg || v_child_owner || '.' || v_child_table ||
                     ' (' || v_count || ' rows); ';
        END IF;
    END LOOP;

    IF v_has_child_rows THEN
        p_result := v_msg;
    ELSE
        p_result := 'No child rows found.';
    END IF;
END;


--
--Below procedure will updates all the child boms data in BOM_HEADER,BOM_LINE_ITEM based on BOM_KEY supplied.
--Dynamically generate the update queries and updates the data. If any input parameter is NULL then it will 
--not include in the UPDATE Query
--
CREATE OR REPLACE PROCEDURE updateChildBomsData ( p_bom_key IN BOM_HEADER.BOM_KEY%TYPE,
p_effective_from_date IN BOM_HEADER.EFFECTIVE_FROM_DT%TYPE,
p_effective_to_date IN BOM_HEADER.EFFECTIVE_TO_DT%TYPE,
p_status IN BOM_HEADER.STATUS%TYPE ) AS

  v_last_bomkey  BOM_HEADER.BOM_KEY%TYPE;
  v_sql       VARCHAR2(4000);
  v_set       VARCHAR2(4000) := NULL;
  v_rows      PLS_INTEGER;
  cur INTEGER;

 CURSOR cur_childBoms IS
    WITH BOM_HIERARCHY (
      LEVEL_NO,
      PARENT_BOM_KEY,
      BOM_KEY,
      SUB_BOM_KEY,
      ITEM_KEY,
      ITEM_QUANTITY,
      EFFECTIVE_FROM_DT,
      EFFECTIVE_TO_DT,
      VERSION,
      BOM_PATH
    ) AS (
      SELECT
        1 AS LEVEL_NO,
        NULL AS PARENT_BOM_KEY,
        bh.BOM_KEY,
        bli.SUB_BOM_KEY,
        bli.ITEM_KEY,
        bli.ITEM_QUANTITY,
        bli.EFFECTIVE_FROM_DT,
        bli.EFFECTIVE_TO_DT,
        bh.VERSION,
        TO_CHAR(bh.BOM_KEY) AS BOM_PATH
      FROM BOM_HEADER bh
      LEFT JOIN BOM_LINE_ITEM bli ON bh.BOM_KEY = bli.BOM_KEY
      WHERE bh.BOM_KEY = p_bom_key
      UNION ALL
      SELECT
        bh.LEVEL_NO + 1,
        bh.BOM_KEY AS PARENT_BOM_KEY,
        bli.BOM_KEY,
        bli.SUB_BOM_KEY,
        bli.ITEM_KEY,
        bli.ITEM_QUANTITY,
        bli.EFFECTIVE_FROM_DT,
        bli.EFFECTIVE_TO_DT,
        bh.VERSION,
        bh.BOM_PATH || '>' || TO_CHAR(bli.BOM_KEY)
      FROM BOM_LINE_ITEM bli
      JOIN BOM_HIERARCHY bh ON bli.BOM_KEY = bh.SUB_BOM_KEY
    )
    SELECT BOM_KEY
    FROM   BOM_HIERARCHY
    ORDER BY LEVEL_NO;

   v_curr_bom_key BOM_HEADER.BOM_KEY%TYPE;
BEGIN

  OPEN cur_childBoms;
  LOOP
    FETCH cur_childBoms INTO v_curr_bom_key;
    EXIT WHEN cur_childBoms%NOTFOUND;

    IF v_last_bomkey IS NULL OR v_last_bomkey <> v_curr_bom_key THEN
        v_sql := 'UPDATE BOM_HEADER SET UPDATE_DT= :p1 ';
        v_sql := v_sql || CASE WHEN p_effective_from_date IS NOT NULL THEN ' ,EFFECTIVE_FROM_DT = :p2 ' END;
        v_sql := v_sql || CASE WHEN p_effective_to_date IS NOT NULL THEN ' ,EFFECTIVE_TO_DT = :p3 ' END;
        v_sql := v_sql || CASE WHEN p_status IS NOT NULL THEN ' ,STATUS = :p4 ' END;
        v_sql := v_sql || ' WHERE BOM_KEY = :p5 ';

        cur := DBMS_SQL.OPEN_CURSOR;
        DBMS_SQL.PARSE(cur, v_sql, DBMS_SQL.NATIVE);

        DBMS_SQL.BIND_VARIABLE(cur, ':p1',      SYSDATE);
        IF p_effective_from_date IS NOT NULL THEN
            DBMS_SQL.BIND_VARIABLE(cur, ':p2',    p_effective_from_date);
        END IF;
        IF p_effective_to_date IS NOT NULL THEN
            DBMS_SQL.BIND_VARIABLE(cur, ':p3',    p_effective_to_date);
        END IF;
        IF p_status IS NOT NULL THEN
            DBMS_SQL.BIND_VARIABLE(cur, ':p4',    p_status);
        END IF;
        DBMS_SQL.BIND_VARIABLE(cur, ':p5', v_curr_bom_key);

        v_rows := DBMS_SQL.EXECUTE(cur);
        DBMS_SQL.CLOSE_CURSOR(cur);

        v_sql := 'UPDATE BOM_LINE_ITEM SET UPDATE_DT= :p1 ';
        v_sql := v_sql || CASE WHEN p_effective_from_date IS NOT NULL THEN ' ,EFFECTIVE_FROM_DT = :p2 ' END;
        v_sql := v_sql || CASE WHEN p_effective_to_date IS NOT NULL THEN ' ,EFFECTIVE_TO_DT = :p3 ' END;
        v_sql := v_sql || ' WHERE BOM_KEY = :p4 ';

        cur := DBMS_SQL.OPEN_CURSOR;
        DBMS_SQL.PARSE(cur, v_sql, DBMS_SQL.NATIVE);

        DBMS_SQL.BIND_VARIABLE(cur, ':p1',      SYSDATE);
        IF p_effective_from_date IS NOT NULL THEN
        DBMS_SQL.BIND_VARIABLE(cur, ':p2',    p_effective_from_date);
        END IF;
        IF p_effective_to_date IS NOT NULL THEN
        DBMS_SQL.BIND_VARIABLE(cur, ':p3',    p_effective_to_date);
        END IF;
        DBMS_SQL.BIND_VARIABLE(cur, ':p4', v_curr_bom_key);

        v_rows := v_rows + DBMS_SQL.EXECUTE(cur);
        DBMS_SQL.CLOSE_CURSOR(cur);

        --DBMS_OUTPUT.PUT_LINE('Rows updated: ' || v_rows);
        v_last_bomkey := v_curr_bom_key;

    END IF;
  END LOOP;
  COMMIT;
  CLOSE cur_childBoms;

EXCEPTION
  WHEN OTHERS THEN
    IF cur_childBoms%ISOPEN THEN
      CLOSE cur_childBoms;
    END IF;
    -- DBMS_OUTPUT.PUT_LINE('Error: ' || SQLCODE || ' - ' || SQLERRM);
    RAISE;
END updateChildBomsData;

CREATE OR REPLACE PROCEDURE TamSchedulerForSingleSupplier(p_fg_ids SYS.ODCINUMBERLIST DEFAULT NULL) IS
     v_tam_allocation_id          NUMBER;
     v_tam_supplier_allocation_id NUMBER;
     v_supplier_key               NUMBER;
 BEGIN
     FOR fg_rec IN (
         SELECT fg.functional_group_id,
                MAX(b.business_entity_key) AS business_entity_key
         FROM functional_group fg
         JOIN item_fg_map m ON m.functional_group_id = fg.functional_group_id
         JOIN item_avl it   ON it.item_key = m.item_key
         JOIN business_entity b ON b.business_entity_key = it.business_entity_key
         JOIN item_master im ON im.item_key = m.item_key
         LEFT JOIN tam_allocation tam
           ON tam.functional_group_id = fg.functional_group_id
          AND tam.site_key = 1
         WHERE tam.tam_allocation_id IS NULL
           AND fg.status = 'ACTIVE'
           AND NOT EXISTS (
               SELECT 1
               FROM item_fg_map m2
               JOIN item_master im2 ON im2.item_key = m2.item_key
               WHERE m2.functional_group_id = fg.functional_group_id
                 AND im2.string_attribute5 = 'Vendor Agnostic Item'
           )
           AND (p_fg_ids IS NULL OR fg.functional_group_id IN (SELECT COLUMN_VALUE FROM TABLE(p_fg_ids)))
         GROUP BY fg.functional_group_id
         HAVING COUNT(DISTINCT b.business_entity_key) = 1
     ) LOOP
         BEGIN
             v_supplier_key := fg_rec.business_entity_key;

             -- Insert into TAM_ALLOCATION
             INSERT INTO TAM_ALLOCATION (
                 TAM_ALLOCATION_ID, FUNCTIONAL_GROUP_ID, SITE_KEY,
                 LAST_CHANGED_ON, LAST_CHANGED_BY, ALLOW_HEDGING,
                 CREATED_ON, CREATED_BY, EXTRACT_FLAG, ROLL_OVER_COUNT,
                 CURRENT_DATA_DELETED, NEXT_ROLLOVER_DATE,
                 DISCP_EXTRACT_FLAG, DISCP_ROLLOVER_EXTRACT_FLAG,
                 LAST_ROLLOVER_DATE, SOURCE_LAST_CHANGED_BY
             )
             VALUES (
                 TAM_ALLOCATION_KEY_SEQ.NEXTVAL,
                 fg_rec.functional_group_id,
                 1, SYSDATE, 'System', 'N',
                 SYSDATE, 'ADMIN', 'P', 0,
                 NULL, NULL, 'P', 'Y', NULL, 'System'
             )
             RETURNING TAM_ALLOCATION_ID INTO v_tam_allocation_id;

             -- Insert into TAM_SUPPLIER_ALLOCATION for fiscal periods
             FOR rec IN (
                 WITH current_month AS (
                     SELECT FISCAL_PERIOD_START_DATE AS start_date,
                            FISCAL_PERIOD_END_DATE   AS end_date
                     FROM fiscal_period
                     WHERE FISCAL_PERIOD_TYPE = 'M'
                       AND TRUNC(SYSDATE) BETWEEN FISCAL_PERIOD_START_DATE AND FISCAL_PERIOD_END_DATE
                 ),
                 next_month AS (
                     SELECT FISCAL_PERIOD_START_DATE AS start_date,
                            FISCAL_PERIOD_END_DATE   AS end_date
                     FROM (
                         SELECT fp.*,
                                ROW_NUMBER() OVER (ORDER BY fp.FISCAL_PERIOD_START_DATE ASC) rn
                         FROM fiscal_period fp
                         WHERE fp.FISCAL_PERIOD_TYPE = 'M'
                           AND fp.FISCAL_PERIOD_START_DATE > TRUNC(SYSDATE)
                     )
                     WHERE rn = 1
                 ),
                 weeks_in_two_months AS (
                     SELECT w.FISCAL_PERIOD_START_DATE AS start_date,
                            w.FISCAL_PERIOD_END_DATE   AS end_date,
                            CASE
                                WHEN w.FISCAL_PERIOD_END_DATE < TRUNC(SYSDATE)
                                     AND w.FISCAL_PERIOD_END_DATE >= TRUNC(SYSDATE) - 14
                                THEN 0 ELSE 100
                            END AS allocation
                     FROM fiscal_period w
                     WHERE w.FISCAL_PERIOD_TYPE = 'W'
                       AND EXISTS (
                           SELECT 1 FROM current_month m
                           WHERE w.FISCAL_PERIOD_START_DATE <= m.end_date
                             AND w.FISCAL_PERIOD_END_DATE   >= m.start_date
                       )
                     UNION ALL
                     SELECT w.FISCAL_PERIOD_START_DATE,
                            w.FISCAL_PERIOD_END_DATE,
                            100
                     FROM fiscal_period w
                     WHERE w.FISCAL_PERIOD_TYPE = 'W'
                       AND EXISTS (
                           SELECT 1 FROM next_month m
                           WHERE w.FISCAL_PERIOD_START_DATE <= m.end_date
                             AND w.FISCAL_PERIOD_END_DATE   >= m.start_date
                       )
                 ),
                 months_after_two AS (
                     SELECT FISCAL_PERIOD_START_DATE AS start_date,
                            FISCAL_PERIOD_END_DATE   AS end_date,
                            100 AS allocation
                     FROM (
                         SELECT fp.*,
                                ROW_NUMBER() OVER (ORDER BY fp.FISCAL_PERIOD_START_DATE ASC) rn
                         FROM fiscal_period fp
                         WHERE fp.FISCAL_PERIOD_TYPE = 'M'
                           AND fp.FISCAL_PERIOD_START_DATE >= TRUNC(SYSDATE)
                     )
                     WHERE rn > 1 AND rn < 12
                 ),
                 fiscal_periods AS (
                     SELECT * FROM weeks_in_two_months
                     UNION ALL
                     SELECT * FROM months_after_two
                 )
                 SELECT v_supplier_key AS business_entity_key,
                        fp.start_date, fp.end_date, fp.allocation
                 FROM fiscal_periods fp
                 ORDER BY fp.start_date
             ) LOOP
                 INSERT INTO TAM_SUPPLIER_ALLOCATION (
                     TAM_SUPPLIER_ALLOCATION_ID, TAM_ALLOCATION_ID,
                     BUSINESS_ENTITY_KEY, START_DATE, END_DATE, ALLOCATION
                 )
                 VALUES (
                     TAM_SUPPLIER_ALLOCATION_KEY_SEQ.NEXTVAL,
                     v_tam_allocation_id,
                     rec.business_entity_key,
                     rec.start_date,
                     rec.end_date,
                     rec.allocation
                 )
                 RETURNING TAM_SUPPLIER_ALLOCATION_ID INTO v_tam_supplier_allocation_id;

                 -- Insert into TAM_ITEM_ALLOCATION
                 FOR item_rec IN (
                     SELECT im.item_key
                     FROM item_fg_map m
                     JOIN item_master im ON im.item_key = m.item_key
                     WHERE m.functional_group_id = fg_rec.functional_group_id
                       AND (im.string_attribute5 IS NULL OR im.string_attribute5 <> 'Vendor Agnostic Item')
                 ) LOOP
                     INSERT INTO TAM_ITEM_ALLOCATION (
                         TAM_ITEM_ALLOCATION_ID, TAM_SUPPLIER_ALLOCATION_ID,
                         ITEM_KEY, ALLOCATION
                     )
                     VALUES (
                         TAM_ITEM_ALLOCATION_KEY_SEQ.NEXTVAL,
                         v_tam_supplier_allocation_id,
                         item_rec.item_key,
                         0
                     );
                 END LOOP;
             END LOOP;

         EXCEPTION
             WHEN NO_DATA_FOUND THEN
                 DBMS_OUTPUT.PUT_LINE('Condition not satisfied for FG ' || fg_rec.functional_group_id);
             WHEN OTHERS THEN
                 ROLLBACK;
                 DBMS_OUTPUT.PUT_LINE('Error processing FG ' || fg_rec.functional_group_id || ': ' || SQLERRM);
         END;
     END LOOP;

     COMMIT;
 EXCEPTION
     WHEN OTHERS THEN
         ROLLBACK;
         DBMS_OUTPUT.PUT_LINE('Fatal error in procedure: ' || SQLERRM);
 END;
